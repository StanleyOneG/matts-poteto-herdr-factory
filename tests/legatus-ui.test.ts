test("native Legatus correction tool safely delivers exact receipt and requires explicit performed-change verification, never worker settlement", async () => {
  const f = await legatusUiFixture();
  try {
    await f.runtime.command("implement-spec=on Correct the approved label");
    await f.startPending();
    let view = await f.state();
    const source = view.snapshot?.submissions[0]; assert.ok(source);
    await f.call("legion_intake", { kind: "new-task", source: { id: source.id, revision: 1 }, goal: "Correct label", acceptance: [], questions: [] });
    const target = (await f.state()).tasks[0]; assert.ok(target);
    const worker = await f.launch({ id: target.id, revision: 1 });
    await f.runtime.settle();
    await f.runtime.command(`correction ${target.id}@1 Use the existing formatter`);
    await f.startPending();
    view = await f.state();
    const original = view.snapshot?.submissions.at(-1); assert.ok(original);
    const id = "2d82bace-a951-4b53-9fb2-f76e73022572";
    const proposal = { kind: "correction", id, source: { id: original.id, revision: 1 }, target: { id: target.id, revision: 1 }, authorization: { kind: "technical" } };
    assert.equal((await f.call("legion_intake", proposal)).details?.kind, "correction-stage");
    const record = (await f.state()).snapshot?.corrections[0]; assert.ok(record?.binding);
    await f.runtime.settle();
    // Targeted command uses intake-only classification; explicit ordinary chat continues the selected native Legatus.
    await f.runtime.emit("input", { source: "interactive", text: "Check and perform the saved formatter correction." });
    await f.startPending();
    const followup = (await f.state()).snapshot?.submissions.at(-1); assert.ok(followup);
    await f.call("legion_intake", { kind: "conversation", source: { id: followup.id, revision: followup.revision } });
    const correction = { id: record.id, digest: record.digest };
    const tool = f.tools.get("legion_correction"); assert.ok(tool);
    assert.equal(tool.exposure, "model-only");
    assert.doesNotMatch(JSON.stringify(tool.parameters), /"legatus"|"generation"|"session"|"run"/);
    assert.equal((await f.call("legion_correction", { correction, action: { kind: "deliver" }, evidence: { session: "worker" } })).isError, true);
    const sent = await f.call("legion_correction", { correction, action: { kind: "deliver" } });
    assert.equal(sent.isError, false, JSON.stringify(sent));
    assert.equal((await f.state()).snapshot?.corrections[0]?.state.kind, "queued");
    assert.equal(worker.prompts.length, 2, "Busy assignment must not be steered or interrupted");
    assert.equal((await f.call("legion_correction", { correction, action: { kind: "verify", summary: "Worker says done", evidence: ["worker-report"] } })).isError, true);
    await worker.settle();
    for (let i = 0; i < 200 && worker.prompts.length < 3; i++) await new Promise(resolve => setTimeout(resolve, 5));
    assert.equal(worker.prompts.length, 3);
    assert.equal(await worker.start(worker.prompts.at(-1) ?? ""), true);
    for (let i = 0; i < 200 && (await f.state()).tasks[0]?.launch.kind !== "reported"; i++) await new Promise(resolve => setTimeout(resolve, 5));
    const reported = (await f.state()).tasks[0]?.launch;
    assert.equal(reported?.kind, "reported", "Safe delivery preserves the immutable report");
    assert.notEqual((await worker.call("write", { path: "corrected", content: "formatted" })).isError, true, "A delivered correction can actually write after the assignment report, before root observation");
    assert.deepEqual((await f.state()).tasks[0]?.launch, reported, "Correction execution must not replay or rewrite launch/report history");
    await worker.settle();
    assert.equal(await worker.start("Unrelated native follow-up is not a pending correction"), true);
    assert.equal((await worker.call("write", { path: "unrelated", content: "forbidden" })).isError, true, "An old delivered correction cannot authorize an arbitrary reported-worker turn");
    await worker.settle();
    await f.runtime.command(`correction observe ${id}`);
    view = await f.state();
    const delivered = view.snapshot?.corrections[0]?.state; assert.equal(delivered?.kind, "delivered");
    if (delivered?.kind !== "delivered") assert.fail("Exact worker receipt required");
    assert.match(delivered.receipt.journal, /worker.jsonl$/);
    assert.ok(delivered.receipt.entry);
    assert.equal((await f.call("legion_intake", proposal)).details?.kind, "correction-stage");
    assert.equal((await f.call("legion_correction", { correction, action: { kind: "deliver" } })).isError, false);
    assert.equal(worker.prompts.length, 3, "Same-ID delivery is observation, never a second worker turn");
    const reissue = await f.call("legion_intake", { ...proposal, id: "2bfc42b2-a6d4-4edb-a7e1-a5ff26c5b7ec", previous: id });
    assert.equal(reissue.details?.kind, "rejected");
    if (reissue.details?.kind !== "rejected") assert.fail("Reissue requires a different addressed current worker");
    assert.equal(reissue.details.code, "correction-replacement", "Applied original source must be available for explicit reissue validation, never stale-source");
    assert.equal((await f.state()).snapshot?.corrections.length, 1);
    assert.equal((await f.call("legion_correction", { correction, action: { kind: "verify", summary: "", evidence: [] } })).isError, true);
    assert.equal((await f.call("legion_correction", { correction, action: { kind: "verify", summary: "Legatus checked actual formatter change", evidence: ["review:formatter-diff", "checks:formatter"] } })).isError, false);
    const applied = (await f.state()).snapshot?.corrections[0]?.state;
    assert.equal(applied?.kind, "applied");
    if (applied?.kind !== "applied") assert.fail("Legatus verification required");
    assert.equal(applied.verification.by.session, "root-legatus");
    assert.deepEqual(applied.verification.evidence, ["review:formatter-diff", "checks:formatter"]);
    await f.runtime.settle();
    assert.equal((await f.call("legion_correction", { correction, action: { kind: "verify", summary: "Forged later turn", evidence: ["prose"] } })).isError, true);
    await f.runtime.command("status");
    assert.match(f.runtime.notices.at(-1) ?? "", /not result acceptance, integration or renewed assignment authority/);
  } finally { await f.close(); }
});

