test("provider diagnostic stderr does not prevent read-only reconciliation of an applied ambiguous delivery", async () => {
  const f = await fixture();
  try {
    const receipts = await remote(f, "lost-diagnostics");
    f.runtime.pi.exec = async (command, args) => {
      const result = spawnSync(command, args, { encoding: "utf8" });
      if (result.status === null) throw result.error ?? new Error(`Unsettled observation: ${result.signal}`);
      return { code: result.status, stdout: result.stdout, stderr: result.stderr, killed: false };
    };
    await accepted(f);
    const final = await finalCandidate(f), id = randomUUID();
    let effects = 0;
    f.runtime.pi.on("tool_call", event => { if (isEffect(event)) effects++; });
    assert.equal((await f.control({ kind: "prepare-publication", id, final, publication: { kind: "draft" } })).isError, false);
    assert.equal((await f.call("legion_deliver", { requestId: id })).isError, true);
    const ambiguous = (await f.state()).snapshot?.deliveries[0]?.state;
    assert.equal(ambiguous?.kind, "unknown");
    assert.match(ambiguous?.message ?? "", /"kind":"exited","code":7/);
    assert.ok(ambiguous?.evidence.some(item => item.includes("Fixture execute diagnostic")), "A nonzero exit retains provider diagnostics without inferring no-effect");
    const before = readFileSync(join(receipts, `${id}.json`), "utf8");
    const reconciled = await f.control({ kind: "reconcile", id });
    assert.equal(reconciled.isError, false, JSON.stringify(reconciled));
    const state = (await f.state()).snapshot?.deliveries[0]?.state;
    assert.equal(state?.kind, "confirmed", JSON.stringify(state));
    assert.ok(state?.evidence.some(item => item.includes("Fixture reconcile diagnostic")), "Provider stderr diagnostics remain available in delivery evidence");
    assert.equal(readFileSync(join(receipts, `${id}.json`), "utf8"), before);
    assert.equal(effects, 1, "Observation must not submit another effect");
  } finally { await f.close(); }
});

test("applied lost delivery acknowledgment reconciles after stopping without replay or worker revival", async () => {
  const f = await fixture();
  try {
    await accepted(f);
    const final = await finalCandidate(f), id = randomUUID();
    let effects = 0;
    f.runtime.pi.on("tool_call", event => { if (isEffect(event)) effects++; });
    const ordinary = f.runtime.ctx.executeTool;
    f.runtime.ctx.executeTool = async (...args) => { const receipt = await ordinary(...args); if (JSON.stringify(args).includes("legion-delivery")) throw new Error("Applied report; acknowledgment lost"); return receipt; };
    await f.control({ kind: "prepare-publication", id, final, publication: { kind: "local-report" } });
    assert.equal((await f.call("legion_deliver", { requestId: id })).isError, true);
    assert.equal((await f.state()).snapshot?.deliveries[0]?.state.kind, "unknown");
    await f.runtime.command("off"); await f.runtime.settle();
    for (let i = 0; i < 200 && (await f.state()).snapshot?.shutdown?.workers.some(worker => worker.state.kind !== "parked"); i++) await new Promise(resolve => setTimeout(resolve, 5));
    const saved = (await f.state()).snapshot; assert.ok(saved);
    const observe = `delivery observe ${saved.id} ${id}`;
    const session = f.runtime.ctx.sessionManager.getSessionId;
    f.runtime.ctx.sessionManager.getSessionId = () => "foreign";
    await f.runtime.command(observe);
    assert.match(f.runtime.notices.at(-1) ?? "", /retained controller session/);
    f.runtime.ctx.sessionManager.getSessionId = session;
    const prompts = [...f.runtime.prompts];
    await f.runtime.command(observe);
    const after = await f.state();
    assert.equal(after.snapshot?.deliveries[0]?.state.kind, "confirmed");
    assert.equal(after.mode, "inactive");
    assert.equal(after.snapshot?.generation, saved.generation);
    assert.deepEqual(after.snapshot?.attachments, saved.attachments);
    assert.deepEqual(after.snapshot?.shutdown, saved.shutdown);
    assert.deepEqual(f.runtime.prompts, prompts);
    assert.equal(effects, 1);
    assert.equal((await f.call("legion_deliver", { requestId: id })).isError, true);
  } finally { await f.close(); }
});

test("restart reconciles an ambiguous applied provider publication read-only under the retained controller", async () => {
  if (process.env.ISSUE39_RESTART_CHILD === "1") {
    const f = await fixture();
    try {
      const receipts = await remote(f, "lost");
      await accepted(f);
      const final = await finalCandidate(f), id = randomUUID();
      await f.control({ kind: "prepare-publication", id, final, publication: { kind: "draft" } });
      assert.equal((await f.call("legion_deliver", { requestId: id })).isError, true);
      assert.equal((await f.state()).snapshot?.deliveries[0]?.state.kind, "unknown");
      await f.runtime.command("off"); await f.runtime.settle();
      for (let i = 0; i < 200 && (await f.state()).snapshot?.shutdown?.workers.some(worker => worker.state.kind !== "parked"); i++) await new Promise(resolve => setTimeout(resolve, 5));
      const saved = (await f.state()).snapshot; assert.ok(saved?.shutdown);
      assert.ok(saved.shutdown.workers.every(worker => worker.state.kind === "parked"));
      const evidence = process.env.ISSUE39_RESTART_EVIDENCE; assert.ok(evidence);
      writeFileSync(evidence, JSON.stringify({ root: f.root, saved, id, receipts }));
    } finally { await f.close(); }
    return;
  }
  const evidence = join(mkdtempSync(join(tmpdir(), "r39-")), "saved.json");
  const setup = spawnSync(process.execPath, ["--import", "tsx", "--test", "--test-name-pattern=restart reconciles an ambiguous", "tests/delivery-public.test.ts"], {
    env: { ...process.env, NODE_TEST_CONTEXT: undefined, ISSUE39_RESTART_CHILD: "1", ISSUE39_RESTART_EVIDENCE: evidence }, encoding: "utf8",
  });
  writeFileSync(`${evidence}.setup.log`, `${setup.stdout}\n${setup.stderr}`);
  writeFileSync(`${evidence}.setup-exit.json`, JSON.stringify({ status: setup.status, signal: setup.signal, error: setup.error?.message }));
  assert.equal(setup.status, 0, `${setup.error?.message ?? ""}\n${setup.stdout}\n${setup.stderr}`);
  // The setup process has exited; the recovery path must acquire, not bypass, its released locks.
  const { root, saved, id, receipts } = JSON.parse(readFileSync(evidence, "utf8"));
  const keys = ["PI_CODING_AGENT_DIR", "PI_SUBAGENT_CHILD", "LEGION_TRIBUNUS_BOOTSTRAP"];
  const prior = Object.fromEntries(keys.map(key => [key, process.env[key]]));
  process.env.PI_CODING_AGENT_DIR = join(root, "a");
  delete process.env.PI_SUBAGENT_CHILD;
  delete process.env.LEGION_TRIBUNUS_BOOTSTRAP;
  const runtime = composedRuntime(saved.context, "root-legatus", join(root, "recovery.jsonl"));
  const before = readFileSync(join(receipts, `${id}.json`), "utf8");
  let observations = 0;
  runtime.pi.exec = async (command, args) => {
    assert.doesNotMatch(JSON.stringify(args), /\\"mode\\":\\"execute\\"|GIT_REFLOG_ACTION=/, "No effect execution in recovery");
    if (JSON.stringify(args).includes("legion-delivery/v1")) observations++;
    const result = spawnSync(command, args, { encoding: "utf8" });
    if (result.status === null) throw result.error ?? new Error(`Unsettled observation: ${result.signal}`);
    return { code: result.status, stdout: result.stdout, stderr: result.stderr, killed: false };
  };
  extension(runtime.pi);
  const state = async () => {
    await runtime.command("status --details");
    const text = runtime.notices.at(-1) ?? "";
    assert.ok(text.includes("State\n"), text);
    return JSON.parse(text.slice(text.indexOf("State\n") + "State\n".length));
  };
  try {
    await runtime.emit("session_start");
    assert.deepEqual((await state()).snapshot, saved, "Restart/status never automatically reconcile");
    const session = runtime.ctx.sessionManager.getSessionId;
    runtime.ctx.sessionManager.getSessionId = () => "foreign";
    await runtime.command(`delivery observe ${saved.id} ${id}`);
    runtime.ctx.sessionManager.getSessionId = session;
    assert.deepEqual((await state()).snapshot, saved);
    await runtime.command(`delivery observe ${saved.id} ${id}`);
    const after = await state();
    assert.equal(after.snapshot.deliveries[0].state.kind, "confirmed");
    assert.equal(after.mode, "inactive");
    assert.equal(after.snapshot.generation, saved.generation);
    assert.deepEqual(after.snapshot.attachments, saved.attachments);
    assert.deepEqual(after.snapshot.shutdown, saved.shutdown);
    assert.equal(readFileSync(join(receipts, `${id}.json`), "utf8"), before);
    assert.equal(observations, 1);
    assert.deepEqual(runtime.prompts, []);
    assert.equal((await runtime.call("legion_deliver", { requestId: id })).isError, true);
    await runtime.command(`delivery observe ${saved.id} ${id}`);
    assert.equal((await state()).snapshot.revision, after.snapshot.revision);
    assert.equal(observations, 1);
  } finally {
    await runtime.emit("session_shutdown");
    for (const [key, value] of Object.entries(prior)) value === undefined ? delete process.env[key] : process.env[key] = value;
  }
});
