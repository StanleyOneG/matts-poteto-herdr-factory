async function fixture(options: { nested?: boolean; linked?: boolean; configured?: boolean } = {}) {
  const f = await legatusUiFixture({ parent: "task-parent", ...options });
  const owning = execFileSync("git", ["-C", f.runtime.ctx.cwd, "rev-parse", "--show-toplevel"], { encoding: "utf8" }).trim();
  mkdirSync(join(owning, ".pi"));
  const gitdir = execFileSync("git", ["-C", owning, "rev-parse", "--absolute-git-dir"], { encoding: "utf8" }).trim();
  const exclude = execFileSync("git", ["-C", owning, "rev-parse", "--path-format=absolute", "--git-path", "info/exclude"], { encoding: "utf8" }).trim();
  // Operator-owned ignored configuration, never generated by a model tool.
  writeFileSync(exclude, ".pi/\n");
  const config = join(owning, ".pi", "provider.json"), selector = join(owning, ".pi", "legion-delivery.json"), reports = join(gitdir, "delivery-reports");
  const configuration = { version: 1, revision: "public-v1", identity: { provider: "local", project: "fixture" }, localReport: { directory: reports } };
  if (options.configured !== false) {
    writeFileSync(config, JSON.stringify(configuration));
    writeFileSync(selector, JSON.stringify({ configurationFile: ".pi/provider.json" }));
  }
  await f.runtime.command("implement-spec=on Implement the approved delivery");
  await f.startPending();
  const source = (await f.state()).snapshot?.submissions[0]; assert.ok(source);
  assert.equal((await f.call("legion_intake", { kind: "new-task", source: { id: source.id, revision: 1 }, goal: "Delivery", acceptance: ["Accepted integration"], questions: [] })).isError, false);
  const saved = (await f.state()).tasks[0]; assert.ok(saved);
  const task = { id: saved.id, revision: 1 };
  return { ...f, owning, config, selector, reports, configuration, task, control: (action: unknown) => f.call("legion_delivery", { action }) };
}
async function accepted(f: Awaited<ReturnType<typeof fixture>>) {
  const worker = await f.launch(f.task);
  writeFileSync(join(worker.ctx.cwd, "result.txt"), "approved content\n");
  execFileSync("git", ["-C", worker.ctx.cwd, "add", "result.txt"]);
  execFileSync("git", ["-C", worker.ctx.cwd, "-c", "user.name=Fixture", "-c", "user.email=fixture@example.test", "commit", "-qm", "result"]);
  await worker.settle(false, "Reported, not accepted");
  for (let i = 0; i < 200 && (await f.state()).tasks[0]?.launch.kind !== "reported"; i++) await new Promise(resolve => setTimeout(resolve, 5));
  const captured = await f.call("legion_result", { action: { kind: "capture", task: f.task, requiredChecks: ["focused"] } });
  assert.ok(captured.details?.kind === "result-stage", JSON.stringify(captured));
  const result = { id: captured.details.result.id, digest: captured.details.result.digest };
  const verified = await f.call("legion_result", { action: { kind: "verify", result, verification: { criteria: [{ criterion: 0, outcome: "passed", evidence: ["criterion.md"] }], checks: [{ name: "focused", outcome: "passed", evidence: ["test.log"] }], exceptions: [] } } });
  assert.ok(verified.details?.kind === "result-stage");
  assert.equal((await f.call("legion_result", { action: { kind: "review", id: randomUUID(), result, verificationDigest: verified.details.result.verifications.at(-1)?.digest, reviewer: { session: "independent", run: "review" }, reference: "review.md", outcome: "approved", evidence: ["exact source"] } })).isError, false);
  const id = randomUUID();
  assert.equal((await f.call("legion_result", { action: { kind: "prepare-integration", result, id } })).isError, false);
  assert.equal((await f.call("legion_integrate", { requestId: id })).isError, false);
  assert.equal((await f.state()).tasks[0]?.resultStatus.kind, "accepted");
  return worker;
}
async function finalCandidate(f: Awaited<ReturnType<typeof fixture>>) {
  const captured = await f.control({ kind: "capture-final", specification: "approved-spec", tasks: [f.task], requiredChecks: ["focused"] });
  assert.ok(captured.details?.kind === "final-delivery-stage", JSON.stringify(captured));
  assert.equal(captured.details.review.kind, "reused-result-review", "Unchanged standalone acceptance reuses its independent review");
  return { id: captured.details.final.id, digest: captured.details.final.digest };
}
const isEffect = (event: { toolName: string; input: unknown }) => event.toolName === "bash" && JSON.stringify(event.input).includes("legion-delivery");

