import assert from "node:assert/strict";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { DatabaseSync } from "node:sqlite";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { resolve, dirname } from "node:path";
import { z } from "zod";
import { stripFrontmatter } from "@earendil-works/pi-coding-agent";
import { Legion } from "../src/intake.ts";
import { GitWorkspace } from "../src/git-workspace.ts";
import { LaunchRecord } from "../src/tribunus.ts";

const Binding = z.object({
  target: z.object({ controller: z.string(), reservation: z.uuid(), scope: z.string(), cwd: z.string(), ledger: z.string(), packageRoot: z.string(), evidenceDirectory: z.string() }),
  owner: z.uuid(), task: z.uuid(), revision: z.int().positive(),
});
const [rootArg, manifestArg] = process.argv.slice(2);
assert.ok(rootArg && manifestArg, "Use <preserved trial directory> <source manifest>. This only observes existing actors.");
const root = resolve(rootArg), binding = Binding.parse(JSON.parse(readFileSync(root + "/target.json")));
const exec = promisify(execFile);
const command = async (args) => JSON.parse((await exec("herdr", args)).stdout);
const read = (path) => JSON.parse(readFileSync(path));
const journalEntries = (path) => readFileSync(path, "utf8").trim().split("\n").map(JSON.parse);
const hash = (bytes) => createHash("sha256").update(bytes).digest("hex");
const recordId = (reference) => reference.split("#").at(-1);
const original = read(binding.target.evidenceDirectory + "/original-start-result.json");
assert.equal(original.reservation, binding.target.reservation);
assert.equal(original.controller, binding.target.controller);
assert.equal(original.original.structuredContent.exit_code, 0);
assert.equal(original.original.structuredContent.truncated, false);
assert.equal(original.original.isError, false);
const originalOutput = JSON.parse(original.original.structuredContent.output);
assert.equal(originalOutput.result.agent.cwd, binding.target.cwd);
assert.equal(originalOutput.result.agent.pane_id, original.window.pane);
assert.equal(originalOutput.result.agent.terminal_id, original.window.terminal);
assert.deepEqual(originalOutput.result.argv, ["pi", "-e", binding.target.packageRoot]);
assert.equal(read(binding.target.evidenceDirectory + "/context.json").controllerMatches, true);
assert.equal(read(binding.target.evidenceDirectory + "/injected.json").launch, original.launch);
assert.equal(read(binding.target.evidenceDirectory + "/selector.json").commandMatches, true);

const db = new DatabaseSync(binding.target.ledger, { readOnly: true });
let record;
try {
  record = LaunchRecord.parse(JSON.parse(db.prepare("SELECT value FROM tribuni WHERE reservation=?").get(binding.target.reservation).value));
  for (const prior of read(root + "/prior-launch-rows.json")) assert.equal(db.prepare("SELECT value FROM tribuni WHERE reservation=?").get(prior.reservation).value, prior.value, "Prior launch history must remain byte-identical");
} finally { db.close(); }
assert.equal(record.id, original.launch);
assert.equal(record.scope, binding.target.scope);
assert.equal(record.startEvidence.kind, "uncertain");
assert.equal(record.state.kind, "reported");
const context = dirname(dirname(dirname(binding.target.ledger)));
const git = new GitWorkspace(context, async (shell) => {
  try { const result = await exec("bash", ["-c", shell], { cwd: context }); return { kind: "finished", code: 0, output: result.stdout }; }
  catch (error) {
    if (typeof error.code === "number" && !error.signal && !error.killed) return { kind: "finished", code: error.code, output: error.stdout + error.stderr };
    return { kind: "unknown", message: String(error) };
  }
});
const legion = new Legion({ storagePath: process.env.HOME + "/.pi/agent/legion", context, session: binding.target.controller, preflight: async () => [], assignments: { workspaceRoot: dirname(binding.target.cwd), repository: () => git } });
const view = await legion.state();
assert.equal(view.snapshot.id, binding.owner);
const task = view.tasks.find((task) => task.id === binding.task);
assert.equal(task.launch.kind, "reported");
assert.equal(task.launch.startEvidence.kind, "uncertain");
assert.equal(task.launch.report.assistantText, record.state.report.assistantText);
const worker = record.state.worker, pane = (await command(["pane", "get", original.window.pane])).result.pane;
assert.equal(pane.terminal_id, original.window.terminal);
assert.equal(pane.foreground_cwd, binding.target.cwd);
assert.equal(worker.resources.cwd, binding.target.cwd);
const processInfo = (await command(["pane", "process-info", "--pane", original.window.pane])).result.process_info;
const initialProcess = read(root + "/worker-pre-trust-process.json").result.process_info;
assert.deepEqual(processInfo.foreground_processes.map((p) => p.pid), initialProcess.foreground_processes.map((p) => p.pid));
assert.equal(processInfo.foreground_processes.length, 1);
const entries = journalEntries(pane.agent_session.value);
assert.equal(entries[0].id, worker.address.session);
const users = entries.filter((entry) => entry.message?.role === "user");
assert.equal(users.length, 2);
const initialization = record.state.initialization;
const body = stripFrontmatter(readFileSync(initialization.skillPath, "utf8")).trim();
const expectedNative = `<skill name="poteto-mode" location="${initialization.skillPath}">\nReferences are relative to ${dirname(initialization.skillPath)}.\n\n${body}\n</skill>\n\nLegion native initialization ${initialization.command}. No implementation assignment is authorized yet. Do not use tools, delegate, edit files, or run commands. Reply in one sentence that you are waiting for the bounded assignment.`;
assert.equal(users[0].message.content[0].text, expectedNative);
assert.equal(initialization.nativePrompt, expectedNative);
assert.equal(task.launch.initialization.nativeExpansionDigest, hash(expectedNative));
const mode = entries.find((entry) => entry.id === recordId(initialization.modeEntry));
const settled = entries.find((entry) => entry.id === recordId(initialization.settledEntry));
assert.equal(mode.customType, "pstack-mode"); assert.equal(mode.data.enabled, true);
assert.equal(settled.customType, "legion-tribunus-settled");
assert.equal(settled.data.command, initialization.command);
assert.equal(settled.data.generation, worker.address.generation);
assert.ok(entries.indexOf(mode) < entries.indexOf(settled));
assert.ok(entries.indexOf(users[0]) < entries.indexOf(settled));
assert.ok(entries.indexOf(settled) < entries.indexOf(users[1]));
assert.ok(users[1].message.content[0].text.startsWith("Legion bounded assignment " + record.state.command));
assert.equal(recordId(record.state.application), users[1].id);
assert.deepEqual(record.state.assignment.task, { id: binding.task, revision: binding.revision });
assert.equal(record.state.assignment.scope, binding.target.scope);
assert.equal(record.state.assignment.authority, "bounded-implementation-only");
const calls = entries.flatMap((entry) => entry.message?.role === "assistant" ? entry.message.content.filter((part) => part.type === "toolCall").map((call) => ({ entry, call })) : []);
assert.equal(calls.length, 1);
assert.ok(entries.indexOf(calls[0].entry) > entries.indexOf(users[1]));
assert.equal(calls[0].call.name, "bash"); assert.equal(calls[0].call.arguments.command, "pwd");
const final = entries.find((entry) => entry.id === recordId(record.state.report.evidence[0]));
assert.equal(final.message.role, "assistant"); assert.equal(final.message.stopReason, "stop");
assert.equal(final.message.content[0].text, record.state.report.assistantText);
assert.ok(final.message.content[0].text.includes(binding.target.cwd.split("/").at(-1)));
assert.ok(entries.filter((entry) => entry.message?.role === "assistant").every((entry) => entry.message.provider === "openai-codex" && entry.message.model === "gpt-6-astra"));
assert.ok(worker.resources.diagnostics.length > 0 && worker.resources.diagnostics.every((d) => d.status === "ready"));
assert.deepEqual(task.launch.worker.resources.skills.map((s) => s.name).sort(), ["code-review", "herdr", "implement", "matt-tdd", "poteto-mode"]);
const attemptRoot = process.env.HOME + "/.pi/agent/legion/tribuni/" + original.launch;
const starts = readdirSync(attemptRoot).filter((file) => file.endsWith(".effect-intent.json")).map((file) => read(attemptRoot + "/" + file)).filter((intent) => intent.command.startsWith("herdr agent start "));
assert.equal(starts.length, 1); assert.equal(starts[0].command, original.command);
const controllerEntries = journalEntries(read(root + "/controller-pre.json").result.pane.agent_session.value);
const rootResult = controllerEntries.find((entry) => entry.message?.role === "toolResult" && entry.message.toolCallId === original.rootCall);
const unknown = JSON.parse(rootResult.message.content[0].text);
assert.equal(unknown.launch.id, original.launch); assert.equal(unknown.launch.startEvidence.kind, "uncertain");
assert.equal(unknown.launch.state.kind, "held");
const nested = rootResult.message.nestedCalls.calls.find((call) => call.id === original.childCall);
assert.equal(nested.status, "error"); assert.ok(nested.error.startsWith("Intentional test-owned loss"));
const actualNestedStarts = controllerEntries.flatMap((entry) => entry.message?.nestedCalls?.calls ?? []).filter((call) => call.arguments?.command === original.command);
assert.equal(actualNestedStarts.length, 1);
const agents = (await command(["agent", "list"])).result.agents;
const before = read(root + "/agents-before.json").result.agents;
assert.equal(agents.filter((agent) => agent.pane_id === original.window.pane).length, 1);
assert.equal(before.some((agent) => agent.pane_id === original.window.pane), false);
const manifest = read(resolve(manifestArg));
for (const [file, expected] of Object.entries(manifest.files)) assert.equal(hash(readFileSync(binding.target.packageRoot + "/" + file)), expected, file);
const result = { verdict: "Verified actual applied-start/lost-receipt trial through public reported state", sourceSha256: manifest.sourceSha256, owner: binding.owner, task: binding.task, reservation: binding.target.reservation, scope: binding.target.scope, attempt: original.launch, window: original.window, cwd: binding.target.cwd, pid: processInfo.foreground_processes[0].pid, session: worker.address.session, generation: worker.address.generation, starts: starts.length, actualNestedStarts: actualNestedStarts.length, workersForPane: 1, originalExitCode: 0, consumerStartEvidence: task.launch.startEvidence.kind, nativeUser: users[0].id, modeEntry: mode.id, initializedSettlement: settled.id, initializationCommand: initialization.command, assignmentCommand: record.state.command, assignmentUser: users[1].id, report: record.state.report, publicPhase: task.launch.kind, journal: pane.agent_session.value, provider: "openai-codex", model: "gpt-6-astra", priorLaunchRowsUnchanged: true };
writeFileSync(root + "/verified-evidence.json", JSON.stringify(result, null, 2));
console.log(JSON.stringify(result, null, 2));
