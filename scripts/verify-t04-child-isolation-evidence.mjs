import assert from "node:assert/strict";
import { readFileSync, realpathSync } from "node:fs";
import { join, resolve } from "node:path";
import { createHash } from "node:crypto";

assert.ok(process.argv[2], "Supply the existing disposable child-isolation trial directory.");
const root = realpathSync(resolve(process.argv[2])), files = new Map();
function bytes(path) {
  const data = readFileSync(path);
  files.set(path, { path, sha256: createHash("sha256").update(data).digest("hex") });
  return data.toString("utf8");
}
const read = name => JSON.parse(bytes(join(root, "evidence", name)));
const trial = read("result.json"), actor = read("actor.json"), principal = read("principal.json"), child = read("child-start.json");
const admission = read("root-admission.json"), result = read("native-result.json"), status = read("status.json"), terminal = read("process-terminal.json");
assert.equal(trial.verdict, "CHILD_ISOLATION_ONLY");
assert.equal(principal.mode, "tui");
assert.equal(admission.parentToolCallId, undefined);
assert.equal(admission.toolName, "subagent");
assert.deepEqual(admission.input, principal.launch);
assert.deepEqual(result.input, principal.launch);
assert.equal(result.toolCallId, admission.toolCallId);
assert.equal(result.isError, false);
assert.equal(result.details.runId, trial.runId);
assert.equal(status.runId, trial.runId);
assert.equal(status.sessionId, principal.journal);
assert.equal(status.state, "complete");
assert.equal(status.steps.length, 1);
const step = status.steps[0];
assert.equal(step.agent, actor.name);
assert.equal(step.model, principal.launch.model);
assert.equal(step.requestedModel, principal.launch.model);
assert.equal(step.launchContractDigest, result.details.launchContractDigest);
assert.equal(step.context, "fresh");
assert.equal(step.launchResolvedExtensions.disableAmbientExtensions, false);
assert.deepEqual(step.launchResolvedExtensions.required, ["legion-child-isolation-trial"]);
assert.deepEqual(step.runtimeAcknowledgedExtensions.ids, ["legion-child-isolation-trial"]);
assert.equal(step.sessionFile, child.journal);
assert.equal(child.cwd, actor.cwd);
assert.equal(child.childMarker, "1");
assert.equal(child.bootstrapUntouched, true);
assert.deepEqual(child.binding, principal.launch.extensionBindings);
assert.notEqual(child.session, principal.session);
const childJournal = bytes(child.journal).trimEnd().split("\n").map(line => JSON.parse(line));
assert.equal(childJournal[0].id, child.session);
assert.equal(childJournal[0].cwd, actor.cwd);
const calls = childJournal.flatMap(entry => entry.message?.role === "assistant" ? entry.message.content.filter(part => part.type === "toolCall") : []);
assert.equal(calls.length, 1);
assert.equal(calls[0].name, "read");
assert.equal(calls[0].arguments.path, join(actor.cwd, "README.md"));
const observed = childJournal.find(entry => entry.message?.role === "toolResult" && entry.message.toolCallId === calls[0].id);
assert.equal(observed.message.isError, false);
assert.equal(observed.message.content[0].text, "Disposable production child-isolation trial.\n");
const parentJournal = bytes(principal.journal).trimEnd().split("\n").map(line => JSON.parse(line));
assert.equal(parentJournal[0].id, principal.session);
const parentCalls = parentJournal.flatMap(entry => entry.message?.role === "assistant" ? entry.message.content.filter(part => part.type === "toolCall" && part.id === admission.toolCallId) : []);
assert.equal(parentCalls.length, 1);
assert.deepEqual(parentCalls[0].arguments, principal.launch);
assert.equal(terminal.state, "observed");
assert.equal(terminal.runId, trial.runId);
assert.equal(terminal.instances.length, 1);
assert.equal(terminal.instances[0].kind, "runner");
assert.equal(terminal.instances[0].processInstanceId, terminal.runnerProcessInstanceId);
assert.equal(terminal.instances[0].exitCode, 0);
assert.equal(terminal.instances[0].signal, null);
const preserved = read("principal-final.json");
assert.equal(preserved.pane.result.pane.terminal_id, actor.pane.terminal_id);
assert.equal(preserved.pane.result.pane.agent_session.value, principal.journal);
for (const file of ["parent.mjs", "child-verifier.mjs", "principal-bootstrap.json"]) bytes(join(root, file));
console.log(JSON.stringify({ verdict: "CHILD_ISOLATION_ONLY", runId: trial.runId, owner: principal.session, child: child.session, childIndex: 0, model: step.model, logicalState: status.state, processState: terminal.state, actor: { name: actor.name, pane: actor.pane.pane_id, preserved: true }, files: [...files.values()], limitations: ["Trial-owned registration and verifier are not production child ownership or a production guard.", "Ambient discovery stayed enabled. No independent permission-denial scenario was run.", "Production role resolution, durable intent, controller authority, post-settlement child accounting, and retained result copies remain unimplemented."] }, null, 2));
